/**
 * Picks a random keyword and a partial-reveal crib for it.
 *
 * No solvability is verified computationally here — see docs/homophonic-cipher-plan.md §3. Within
 * one block, a single correctly-identified letter/number correspondence (found via ordinary
 * frequency/pattern analysis on the ciphertext) reveals that entire block, the same way Aristocrat
 * is solvable with zero given key. So, like every other cipher in this app, solvability rests on
 * adequate ciphertext length and real English text, not a computed property of the crib alone.
 *
 * Ordered reveals (position given) are a bigger head start than they look — revealing one letter's
 * position hands over its entire 25-code block. Unordered reveals require real cross-referencing
 * against the ciphertext to resolve, closer to genuine "hypothesis testing."
 *
 * @returns {{ keyword: string, cribDisplay: string }}
 */
export function generateHomophonicCrib() {
  const keyword = HOMOPHONIC_KEYWORDS[Math.floor(Math.random() * HOMOPHONIC_KEYWORDS.length)];
  const revealCount = Math.random() < 0.5 ? 2 : 3;
  const ordered = Math.random() < 0.5;

  const positions = [0, 1, 2, 3];
  for (let i = positions.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [positions[i], positions[j]] = [positions[j], positions[i]];
  }
  const revealedPositions = positions.slice(0, revealCount).sort((a, b) => a - b);

  let cribDisplay;
  if (ordered) {
    const slots = ['_', '_', '_', '_'];
    for (const pos of revealedPositions) slots[pos] = keyword[pos];
    cribDisplay = slots.join(' ');
  } else {
    const letters = revealedPositions.map((pos) => keyword[pos]);
    cribDisplay = `contains ${letters.join(', ')} (in some order)`;
  }

  return { keyword, cribDisplay };
}
